#!/usr/bin/env bash
# ============================================================================
# setup-codeapi.sh – code interpreter for KIRA on an own server with KVM (not on the KIRA server)
#   bash /opt/codeinterpreter/setup-codeapi.sh            set up / update and start
# Needs: Linux with /dev/kvm (hardware virtualisation, not nested in a VM without it), Docker, Compose ≥ 2.24, git,
# openssl, and /opt/codeinterpreter/jwks.json – the public key of KIRA (/opt/kira/config/codeapi-jwks.json).
# Secrets are generated once into /opt/codeinterpreter/.env (600). The project is built from source (first build
# takes a while: it compiles the language runtimes of the sandbox).
# ============================================================================
set -euo pipefail
DIR=/opt/codeinterpreter
VERSION=${CODEAPI_VERSION:-v1.9.1}           # tagged release of ClickHouse/code-interpreter
die() { printf 'Error: %s\n' "$*" >&2; exit 1; }
info() { printf '%s\n' "$*"; }

[ "$(id -u)" = 0 ] || die "please run as root."
[ -e /dev/kvm ] || die "/dev/kvm is missing – this server cannot run the KVM sandbox (hardware virtualisation needed)."
for c in docker git openssl; do command -v "$c" >/dev/null || die "program '$c' is missing."; done
v=$(docker compose version --short 2>/dev/null | sed 's/^v//') || die "Docker Compose (plugin) is missing."
printf '%s\n%s\n' 2.24.0 "$v" | sort -V -C || die "Docker Compose $v is too old – at least 2.24 is required."
[ -s "$DIR/jwks.json" ] || die "$DIR/jwks.json is missing – copy /opt/kira/config/codeapi-jwks.json from the KIRA server."
python3 -c 'import json,sys; k=json.load(open(sys.argv[1]))["keys"][0]; assert k["crv"]=="Ed25519" and k["kid"]' \
  "$DIR/jwks.json" 2>/dev/null || die "$DIR/jwks.json is not a valid key file of KIRA."

if [ ! -d "$DIR/src/.git" ]; then
  info "Cloning ClickHouse/code-interpreter $VERSION …"
  git clone --depth 1 --branch "$VERSION" https://github.com/ClickHouse/code-interpreter "$DIR/src"
else
  cur=$(git -C "$DIR/src" describe --tags 2>/dev/null || echo "?")
  if [ "$cur" != "$VERSION" ]; then
    info "Updating from $cur to $VERSION …"
    git -C "$DIR/src" fetch --depth 1 origin tag "$VERSION" && git -C "$DIR/src" checkout -q "$VERSION"
  fi
fi

ENV=$DIR/.env
if [ ! -f "$ENV" ]; then
  umask 077
  priv=$(openssl genpkey -algorithm ed25519 -outform DER | base64 -w0)
  pub=$(printf '%s' "$priv" | base64 -d | openssl pkey -inform DER -pubout -outform DER | base64 -w0)
  cat > "$ENV" <<EOT
# code interpreter for KIRA – generated by setup-codeapi.sh (secrets – do not share)
BIND_IP=0.0.0.0
API_PORT=3112
KVM_ENABLED=true
REDIS_PASSWORD=$(openssl rand -hex 24)
MINIO_ROOT_USER=codeapi$(openssl rand -hex 4)
MINIO_ROOT_PASSWORD=$(openssl rand -hex 24)
CODEAPI_INTERNAL_SERVICE_TOKEN=$(openssl rand -hex 32)
CODEAPI_EGRESS_GRANT_SECRET=$(openssl rand -hex 32)
CODEAPI_BRIDGE_TOKEN=$(openssl rand -hex 32)
CODEAPI_EXECUTION_MANIFEST_PRIVATE_KEY=$priv
SANDBOX_EXECUTION_MANIFEST_PUBLIC_KEY=$pub
EOT
  info "$ENV created (secrets). Set BIND_IP to the address KIRA connects to, if the server has several."
fi
# public key of KIRA – on every run, so a new key from the KIRA server only needs a copy and this script
jwks=$(python3 -c 'import json,sys; print(json.dumps(json.load(open(sys.argv[1])), separators=(",", ":")))' "$DIR/jwks.json")
grep -v '^CODEAPI_JWT_JWKS_JSON=' "$ENV" > "$ENV.tmp" || true
printf "CODEAPI_JWT_JWKS_JSON='%s'\n" "$jwks" >> "$ENV.tmp"
chmod 600 "$ENV.tmp"; mv "$ENV.tmp" "$ENV"

cd "$DIR"
info "Building and starting (first build can take 30 minutes or more) …"
docker compose -p codeinterpreter -f src/docker-compose.yaml -f compose.kira.yml --env-file "$ENV" up -d --build
port=$(sed -n 's/^API_PORT=//p' "$ENV")
for i in $(seq 60); do
  curl -fsS "http://127.0.0.1:${port:-3112}/v1/health" >/dev/null 2>&1 && { info "API healthy: http://<this server>:${port:-3112}/v1/health"; break; }
  sleep 5
done
info "Next: in /opt/kira/env/setup.env on the KIRA server CODE_INTERPRETER=true and CODE_API_URL=http://<this server>:${port:-3112},"
info "then bash /opt/kira/setup.sh – and allow port ${port:-3112} on this server only from the KIRA server."
